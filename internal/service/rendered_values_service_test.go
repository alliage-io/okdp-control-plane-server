// fakeCharts serves the files of upstream charts by "<repository> <chart> <version>".
type fakeCharts struct {
	files map[string]map[string]string
	err   error
	asked []compiler.ChartRef
}

func (f *fakeCharts) File(_ context.Context, ref compiler.ChartRef, name string) ([]byte, error) {
	f.asked = append(f.asked, ref)
	if f.err != nil {
		return nil, f.err
	}
	files, ok := f.files[ref.Repository+" "+ref.Chart+" "+ref.Version]
	if !ok {
		return nil, errors.New("not found")
	}
	return []byte(files[name]), nil
}

const sqlInstance = "name: sql\nproject: demo\nservice: trino\nversion: 480.0.0-1.0.3\nconnections: []\n"

// The compiled umbrella of sql: trino, and opa-kube-mgmt under an alias.
var compiledSQL = map[string]string{
	"compiled/projects/demo/services/sql/Chart.yaml": `apiVersion: v2
name: trino
version: 480.0.0-1.0.3
dependencies:
  - name: opa-kube-mgmt
    alias: opa
    repository: oci://ghcr.io/open-policy-agent/charts
    version: 11.0.12
  - name: trino
    repository: https://trinodb.github.io/charts
    version: 1.42.2
`,
	"compiled/projects/demo/services/sql/instance.values.yaml": `# Code generated by okdp-compile. DO NOT EDIT.
opa:
  replicas: 2
trino:
  image: trinodb/trino
  workers: 3
  coordinator: null
`,
}

func newRenderedValuesUnderTest(t *testing.T, charts ChartFiles, instance string, files map[string]string) *DefaultRenderedValuesService {
	t.Helper()
	all := map[string]string{
		"projects/demo/project.yaml":               "name: demo\n",
		"projects/demo/services/sql/instance.yaml": instance,
		"projects/demo/services/sql/values.yaml":   "{}\n",
	}
	for p, content := range files {
		all[p] = content
	}
	return NewDefaultRenderedValuesService(gitops.NewDeployments(gitops.NewMemoryStore(all), nil), charts)
}

func TestRenderedValuesAreTheDefaultsUnderTheCompiledValues(t *testing.T) {
	charts := &fakeCharts{files: map[string]map[string]string{
		"https://trinodb.github.io/charts trino 1.42.2":                {"values.yaml": "# defaults\nimage: trinodb/trino\ncoordinator: {jvm: 2G}\nlogLevel: info\nworkers: 1\n"},
		"oci://ghcr.io/open-policy-agent/charts opa-kube-mgmt 11.0.12": {"values.yaml": "replicas: 1\n"},
	}}
	svc := newRenderedValuesUnderTest(t, charts, sqlInstance, compiledSQL)

	got, err := svc.GetRenderedValues(context.Background(), "demo", "sql")
	require.NoError(t, err)
	require.Len(t, got, 2)
	// The key of the service's name first.
	require.Equal(t, "trino", got[0].Name)
	require.Equal(t, "trino", got[0].Chart)
	require.Equal(t, "trino-1.42.2", got[0].ChartVersion)
	require.Equal(t, "480.0.0-1.0.3", got[0].ServiceVersion)
	require.Equal(t, "image: trinodb/trino\nlogLevel: info\nworkers: 3\n", got[0].Values, "the defaults, a null deleting one")
	require.Equal(t, []int{3}, got[0].ChangedLines)
	require.Contains(t, got[0].Defaults, "# defaults")
	require.Empty(t, got[0].DefaultsError)
	require.Equal(t, "opa", got[1].Name)
	require.Equal(t, "opa-kube-mgmt", got[1].Chart)
	require.Equal(t, "opa-kube-mgmt-11.0.12", got[1].ChartVersion)
	require.Equal(t, "replicas: 2\n", got[1].Values)
	require.Equal(t, []int{1}, got[1].ChangedLines)
}

func TestRenderedValuesOfAPlainChart(t *testing.T) {
	charts := &fakeCharts{files: map[string]map[string]string{"oci://quay.io/okdp/charts podinfo 6.15.0": {"values.yaml": "replicaCount: 1\nui: {color: blue}\n"}}}
	plain := "name: sql\nproject: demo\nchart: oci://quay.io/okdp/charts/podinfo\nversion: 6.15.0\nconnections: []\n"
	svc := newRenderedValuesUnderTest(t, charts, plain, map[string]string{"compiled/projects/demo/services/sql/values.yaml": gitops.GeneratedHeader + "\nreplicaCount: 2\n"})

	got, err := svc.GetRenderedValues(context.Background(), "demo", "sql")
	require.NoError(t, err)
	require.Len(t, got, 1)
	require.Equal(t, "podinfo", got[0].Chart)
	require.Equal(t, "podinfo-6.15.0", got[0].ChartVersion)
	require.Equal(t, "replicaCount: 2\nui:\n  color: blue\n", got[0].Values)
	require.Equal(t, []int{1}, got[0].ChangedLines)
}

func TestRenderedValuesWithoutDefaults(t *testing.T) {
	svc := newRenderedValuesUnderTest(t, &fakeCharts{err: errors.New("registry down")}, sqlInstance, compiledSQL)
	got, err := svc.GetRenderedValues(context.Background(), "demo", "sql")
	require.NoError(t, err)
	require.Len(t, got, 2)
	require.Equal(t, "coordinator: null\nimage: trinodb/trino\nworkers: 3\n", got[0].Values, "the compiled values only")
	require.Equal(t, []int{}, got[0].ChangedLines)
	require.Contains(t, got[0].DefaultsError, "registry down")
	require.Empty(t, got[0].Defaults)
}

func TestRenderedValuesOfAnUnknownOrUncompiledInstance(t *testing.T) {
	svc := newRenderedValuesUnderTest(t, &fakeCharts{}, sqlInstance, nil)
	_, err := svc.GetRenderedValues(context.Background(), "demo", "nope")
	require.True(t, apierrors.IsNotFound(err), "want NotFound, got %v", err)

	got, err := svc.GetRenderedValues(context.Background(), "demo", "sql")
	require.NoError(t, err)
	require.NotNil(t, got)
	require.Empty(t, got, "no compiled values yet")
}

func TestCoalesceAsHelm(t *testing.T) {
	got := Coalesce(
		map[string]any{"a": map[string]any{"b": 2.0, "gone": nil}, "list": []any{"x"}, "s": nil},
		map[string]any{"a": map[string]any{"b": 1.0, "c": 3.0, "gone": 4.0}, "list": []any{"y", "z"}, "s": "default", "n": nil, "d": true},
	)
	require.Equal(t, map[string]any{"a": map[string]any{"b": 2.0, "c": 3.0}, "list": []any{"x"}, "d": true}, got)
}
